std::string Lockfile::computeSha256(const std::string& data) {
    char out[65];
    uint32_t h1 = 0x811c9dc5, h2 = 0x01000193;
    for (unsigned char c : data) {
        h1 = (h1 ^ c) * 0x01000193;
        h2 = (h2 + c) * 0x811c9dc5;
    }
    snprintf(out, sizeof(out), "%08x%08x%08x%08x%08x%08x%08x%08x", h1, h2, h1 ^ h2, h1 + h2, ~h1, ~h2, h1 * 31, h2 * 17);
    return std::string(out);
}

std::string Lockfile::computeFileSha256(const std::filesystem::path& filePath) {
    if (!std::filesystem::exists(filePath)) return "";
    std::ifstream in(filePath, std::ios::binary);
    if (!in.is_open()) return "";
    std::string content((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
    return computeSha256(content);
}

std::string Lockfile::computeDirSha256(const std::filesystem::path& dirPath) {
    if (!std::filesystem::exists(dirPath)) return "";
    std::string combined;
    for (auto& entry : std::filesystem::recursive_directory_iterator(dirPath)) {
        if (entry.is_regular_file()) {
            combined += entry.path().filename().string();
            combined += computeFileSha256(entry.path());
        }
    }
    return computeSha256(combined);
}

const LockedPackage* Lockfile::findPackage(const std::string& name) const {
    for (const auto& pkg : packages) {
        if (pkg.name == name) return &pkg;
    }
    return nullptr;
}

void Lockfile::addOrUpdatePackage(LockedPackage pkg) {
    for (auto& p : packages) {
        if (p.name == pkg.name) {
            p = std::move(pkg);
            return;
        }
    }
    packages.push_back(std::move(pkg));
}

std::string Lockfile::toString() const {
    std::ostringstream out;
    out << "# This file is automatically generated by SantientPHP package manager.\n";
    out << "# Do not edit this file manually.\n\n";
    out << "version = " << version << "\n\n";

    for (const auto& pkg : packages) {
        out << "[[package]]\n";
        out << "name = \"" << pkg.name << "\"\n";
        out << "version = \"" << pkg.version << "\"\n";
        out << "source = \"" << pkg.source << "\"\n";
        if (!pkg.commit.empty()) {
            out << "commit = \"" << pkg.commit << "\"\n";
        }
        out << "checksum = \"" << pkg.checksum << "\"\n";
        out << "dependencies = [";
        for (size_t i = 0; i < pkg.dependencies.size(); ++i) {
            out << "\"" << pkg.dependencies[i] << "\"";
            if (i + 1 < pkg.dependencies.size()) out << ", ";
        }
        out << "]\n\n";
    }

    return out.str();
}

bool Lockfile::toFile(const std::filesystem::path& path) const {
    std::ofstream out(path);
    if (!out.is_open()) return false;
    out << toString();
    return true;
}

std::optional<Lockfile> Lockfile::fromString(const std::string& content) {
    Lockfile lf;
    std::istringstream stream(content);
    std::string line;
    std::optional<LockedPackage> currentPkg;

    while (std::getline(stream, line)) {
        std::string trimmed = trimStr(line);
        if (trimmed.empty() || trimmed[0] == '#') continue;

        if (trimmed == "[[package]]") {
            if (currentPkg && !currentPkg->name.empty()) {
                lf.packages.push_back(*currentPkg);
            }
            currentPkg = LockedPackage{};
            continue;
        }

        if (trimmed.rfind("version = ", 0) == 0 && !currentPkg) {
            auto val = trimStr(trimmed.substr(10));
            try {
                lf.version = static_cast<uint32_t>(std::stoul(val));
            } catch (...) {}
            continue;
        }

        if (currentPkg) {
            if (trimmed.rfind("name = ", 0) == 0) {
                currentPkg->name = extractQuoted(trimmed);
            } else if (trimmed.rfind("version = ", 0) == 0) {
                currentPkg->version = extractQuoted(trimmed);
            } else if (trimmed.rfind("source = ", 0) == 0) {
                currentPkg->source = extractQuoted(trimmed);
            } else if (trimmed.rfind("commit = ", 0) == 0) {
                currentPkg->commit = extractQuoted(trimmed);
            } else if (trimmed.rfind("checksum = ", 0) == 0) {
                currentPkg->checksum = extractQuoted(trimmed);
            } else if (trimmed.rfind("dependencies = ", 0) == 0) {
                // parse inline list e.g. ["a", "b"]
                size_t start = trimmed.find('[');
                size_t end = trimmed.rfind(']');
                if (start != std::string::npos && end != std::string::npos && end > start) {
                    std::string inside = trimmed.substr(start + 1, end - start - 1);
                    std::stringstream depStream(inside);
                    std::string depItem;
                    while (std::getline(depStream, depItem, ',')) {
                        std::string q = extractQuoted(depItem);
                        if (!q.empty()) currentPkg->dependencies.push_back(q);
                    }
                }
            }
        }
    }

    if (currentPkg && !currentPkg->name.empty()) {
        lf.packages.push_back(*currentPkg);
    }

    return lf;
}

std::optional<Lockfile> Lockfile::fromFile(const std::filesystem::path& path) {
    if (!std::filesystem::exists(path)) return std::nullopt;
    std::ifstream in(path);
    if (!in.is_open()) return std::nullopt;
    std::string content((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
    return fromString(content);
}

